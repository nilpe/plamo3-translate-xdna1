#!/usr/bin/env python3
"""Workstation side of L3/L4: order-matched CPU reference (ref_step.py of the PoC, the same independent reference that certified the W4 decode) vs the NPU logits of the shipped long runtime.
  l3a   old positions, stored expected logits (generated by the same reference from the same dump)  -> compares l3_<pos>.bin with phase2-runs/expect<pos>.bin
  l3b   new positions with iGPU KV                                                                   -> runs the reference on the fetched dump, compares with l3b_<N>.bin
  l4    continuous-decode captures: for every captured position runs the reference on the dump taken before the step and compares with the NPU logits of that step
Bitwise = identical bytes of the BF16 logits vector (107,520 x 2 bytes). Writes a JSON report and exits non-zero on any difference."""
import json, subprocess, sys, time
from pathlib import Path
import numpy as np
ROOT = Path('/home/ykogi/workspace/plamo3-fast-inference-by-xdna')
D = ROOT / 'poc/pd256k/d'
PY = str(ROOT / 'runs/r29/cpu-env/bin/python')
TOK = np.load(ROOT / 'poc/pd256k/p/data/tokens_262k.npy')
def ref(pos, token, dump, out):
    t0 = time.time()
    r = subprocess.run(['systemd-run', '--user', '--scope', '-q', '-p', 'MemoryMax=8G', '-p', 'MemorySwapMax=0', PY, str(D / 'ref_step.py'), '--expect', '--pos', str(pos), '--token', str(token), '--kv-dump', str(dump), '--out', str(out)], capture_output=True, text=True, cwd=str(D))
    if r.returncode != 0: raise SystemExit('reference failed: ' + r.stderr[-300:])
    return time.time() - t0
def main():
    mode, base = sys.argv[1], Path(sys.argv[2]).resolve(); rows = []
    if mode == 'l3a':
        for pos in (2047, 2048, 2050, 4096, 65536, 262143):
            a = (base / f'l3_{pos}.bin').read_bytes(); b = (D / f'phase2-runs/expect{pos}.bin').read_bytes()
            rows.append(dict(pos=pos, history='real NPU history' if pos <= 4096 else 'seeded synthetic', bitwise=a == b, bytes=len(a)))
    elif mode == 'l3b':
        for n in map(int, sys.argv[3].split(',')):
            tok = int(TOK[n]); out = base / f'ref_{n}.bin'; secs = ref(n, tok, base / f'l3b_{n}' / 'kv-out', out)
            a = (base / f'l3b_{n}.bin').read_bytes(); b = out.read_bytes()
            rows.append(dict(pos=n, history='iGPU prefill KV', token=tok, bitwise=a == b, bytes=len(a), ref_s=round(secs, 1)))
    elif mode == 'l4':
        for run in sys.argv[3].split(','):
            d = base / f'l4_{run}'; s = json.loads((d / 'summary.json').read_text())
            for c in s['captured']:
                pos = c['pos']; out = d / f'ref_{pos}.bin'; secs = ref(pos, c['token'], d / f'dump_{pos}', out)
                a = (d / f'logits_{pos}.bin').read_bytes(); b = out.read_bytes()
                rows.append(dict(run=run, prompt=s['prompt'], pos=pos, token=c['token'], bitwise=a == b, ref_s=round(secs, 1), compaction_step=(pos >= 4096 and pos % 2048 == 0)))
    res = dict(mode=mode, rows=rows, PASS=bool(rows) and all(r['bitwise'] for r in rows))
    (base / f'cpu_{mode}.json').write_text(json.dumps(res, indent=1))
    for r in rows: print(r)
    print('PASS' if res['PASS'] else 'FAIL'); return 0 if res['PASS'] else 1
if __name__ == '__main__':
    sys.exit(main())
